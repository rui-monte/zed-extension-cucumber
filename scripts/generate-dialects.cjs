'use strict';

const fs = require('node:fs');
const path = require('node:path');
const dialects = require('../managed-server/node_modules/@cucumber/gherkin/dist/src/gherkin-languages.json');
const tokenNames = ['and', 'background', 'but', 'examples', 'feature', 'given', 'rule', 'scenario', 'scenarioOutline', 'then', 'when'];

// Build a character trie before compressing it. Inserting an existing prefix
// into an already-compressed trie can create empty, duplicate branches (e.g.
// Portuguese Cenário / Cenários / Cenário de Fundo in the upstream table).
function trie(entries) {
  const root = { children: new Map(), value: 0 };
  for (const [word, value] of entries) {
    let node = root;
    for (const character of word) {
      const code = character.codePointAt(0);
      if (!node.children.has(code)) node.children.set(code, { children: new Map(), value: 0 });
      node = node.children.get(code);
    }
    node.value = value;
  }
  const nodes = [];
  function append(children) {
    const start = nodes.length + 1;
    for (let [code, node] of [...children].sort(([a], [b]) => a - b)) {
      const prefix = [code];
      while (node.value === 0 && node.children.size === 1) {
        [code, node] = [...node.children][0];
        prefix.push(code);
      }
      nodes.push({ prefix, node });
    }
    return children.size ? start : 0;
  }
  append(root.children);
  const arrays = { prefix_raw: [], prefix_indexes: [], prefix_sizes: [], i_p1s: [], sizes: [], values: [] };
  for (const { prefix, node } of nodes) {
    arrays.prefix_indexes.push(arrays.prefix_raw.length);
    arrays.prefix_raw.push(...prefix);
    arrays.prefix_sizes.push(prefix.length);
    arrays.i_p1s.push(append(node.children));
    arrays.sizes.push(node.children.size);
    arrays.values.push(node.value);
  }
  return { arrays, rootSize: root.children.size };
}

function render(name, type, entries) {
  const { arrays, rootSize } = trie(entries);
  const lines = Object.entries(arrays).map(([key, values]) => {
    const suffix = key === 'prefix_raw' ? 'Label' : key === 'values' ? 'Value' : 'Size';
    return `static const ${type}${suffix} ${name}_${key}[] = {${values.join(',')}};`;
  });
  lines.push(`static const ${type} ${name} = {${Object.keys(arrays).map((key) => `${name}_${key}`).join(',')},${rootSize}};`);
  return lines.join('\n');
}

const languages = Object.keys(dialects).sort();
const identifier = (name) => name.replaceAll('-', '_') + '_dialect';
const output = ['// Generated by scripts/generate-dialects.cjs from the pinned @cucumber/gherkin package.', '#include "dialect.h"'];
for (const language of languages) {
  const entries = tokenNames.flatMap((name, index) => dialects[language][name].filter((word) => word !== '* ').map((word) => [word, index + 1]));
  output.push(render(identifier(language), 'Dialect', entries));
}
output.push(render('language', 'Language', languages.map((language, index) => [language, index + 1])));
output.push(`const Dialect *Dialect_for(LanguageValue language) {\n  switch (language) {\n${languages.map((language, index) => `  case ${index + 1}: return &${identifier(language)};`).join('\n')}\n  default: return &en_dialect;\n  }\n}`);
output.push('IMPL_ARRAY_TRIE(Dialect, DialectLabel, DialectSize, DialectValue);', 'IMPL_ARRAY_TRIE(Language, LanguageLabel, LanguageSize, LanguageValue);');
const file = path.resolve(__dirname, '../grammar/src/gherkin/dialect.c');
const content = output.join('\n\n') + '\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== content) throw new Error('Dialect table is stale. Run node scripts/generate-dialects.cjs');
} else {
  fs.writeFileSync(file, content);
}
